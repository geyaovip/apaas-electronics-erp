import 'dotenv/config';
import assert from 'node:assert/strict';

const base = process.env.TEST_API_URL || 'http://127.0.0.1:4501/api/v1';
const tag = Date.now().toString(36);
const password = `Erp-Batch-${tag}-Strong!`;
let cookie = '';
async function request(path, body) {
  const response = await fetch(base + path, { method: body === undefined ? 'GET' : 'POST', headers: { ...(body === undefined ? {} : { 'content-type': 'application/json' }), ...(cookie ? { cookie } : {}) }, body: body === undefined ? undefined : JSON.stringify(body) });
  return { status: response.status, value: await response.json(), cookie: response.headers.get('set-cookie')?.split(';')[0] ?? '' };
}
async function ok(path, body) { const result = await request(path, body); assert.ok(result.status >= 200 && result.status < 300, `${path}: ${JSON.stringify(result.value)}`); return result.value; }
async function login(email, secret) { const result = await request('/auth/login', { workspace: 'default', email, password: secret }); assert.equal(result.status, 201); cookie = result.cookie; }

await login(process.env.ERP_BOOTSTRAP_EMAIL, process.env.ERP_BOOTSTRAP_PASSWORD);
for (const role of ['sales', 'purchasing', 'warehouse', 'finance']) await ok('/admin/users', { name: `${role}-${tag}`, email: `batch-${role}-${tag}@test.local`, password, role });
const buyer = `batch-purchasing-${tag}@test.local`;
const keeper = `batch-warehouse-${tag}@test.local`;
const seller = `batch-sales-${tag}@test.local`;
const accountant = `batch-finance-${tag}@test.local`;
await login(buyer, password);
const p1 = await ok('/products', { sku: `PCB-${tag}`, name: '控制板', purchase_price: '10.00', sale_price: '30.00', reorder_point: 2 });
const p2 = await ok('/products', { sku: `CASE-${tag}`, name: '外壳', purchase_price: '20.00', sale_price: '40.00' });
const supplier = await ok('/suppliers', { code: `SUP-${tag}`, name: '批次供应商' });
const purchase = await ok('/purchases', { number: `PO-${tag}`, supplier_id: supplier.id, lines: [{ product_id: p1.id, quantity: 5 }, { product_id: p2.id, quantity: 3 }] });
await ok(`/purchases/${purchase.id}/confirm`, { version: purchase.version });
await login(seller, password);
const customer = await ok('/customers', { code: `CUS-${tag}`, name: '分批交付客户' });
const contract = await ok('/contracts', { number: `SC-${tag}`, customer_id: customer.id, lines: [{ product_id: p1.id, quantity: 4 }, { product_id: p2.id, quantity: 2 }] });
await ok(`/contracts/${contract.id}/confirm`, { version: contract.version });
assert.equal((await request(`/purchases/${purchase.id}/receive`, { version: 2 })).status, 403);
await login(keeper, password);
let purchaseDetail = await ok(`/purchases/${purchase.id}`);
const pl1 = purchaseDetail.lines.find(line => line.productId === p1.id);
const pl2 = purchaseDetail.lines.find(line => line.productId === p2.id);
assert.equal((await request(`/contracts/${contract.id}/ship`, { version: 2, lines: [{ line_id: (await ok(`/contracts/${contract.id}`)).lines[0].id, quantity: 1 }] })).status, 409, 'stock shortage must roll back shipment');
const firstReceipt = await ok(`/purchases/${purchase.id}/receive`, { version: 2, document_number: `GRN-${tag}-1`, lines: [{ line_id: pl1.id, quantity: 2 }] });
assert.equal(firstReceipt.status, 'partial_received');
assert.equal(firstReceipt.lines.find(line => line.id === pl1.id).receivedQty, 2);
assert.equal(Number(firstReceipt.payable.amount), 20);
assert.equal((await request(`/purchases/${purchase.id}/receive`, { version: 2, lines: [{ line_id: pl1.id, quantity: 1 }] })).status, 409, 'stale version must be rejected');
assert.equal((await request(`/purchases/${purchase.id}/receive`, { version: 3, lines: [{ line_id: pl1.id, quantity: 4 }] })).status, 409, 'overreceipt must be rejected');
assert.equal((await request(`/purchases/${purchase.id}/receive`, { version: 3, document_number: `GRN-${tag}-1`, lines: [{ line_id: pl1.id, quantity: 1 }] })).status, 409, 'duplicate document number must be rejected');
await login(accountant, password);
let payable = (await ok('/finance/payables')).find(account => account.orderId === purchase.id);
await ok(`/finance/payables/${payable.id}/payments`, { amount: '20.00', reference: `PAY-${tag}` });
assert.equal((await request(`/finance/payables/${payable.id}/payments`, { amount: '1.00', reference: `PAY-${tag}` })).status, 409, 'duplicate payable reference must be rejected');
await login(keeper, password);
const finalReceipt = await ok(`/purchases/${purchase.id}/receive`, { version: 3, document_number: `GRN-${tag}-2`, lines: [{ line_id: pl1.id, quantity: 3 }, { line_id: pl2.id, quantity: 3 }] });
assert.equal(finalReceipt.status, 'received');
assert.equal(Number(finalReceipt.payable.amount), 110);
assert.equal(finalReceipt.payable.status, 'partial');
purchaseDetail = await ok(`/purchases/${purchase.id}`);
assert.equal(purchaseDetail.stockDocuments.length, 2);
const contractDetail = await ok(`/contracts/${contract.id}`);
const sl1 = contractDetail.lines.find(line => line.productId === p1.id);
const sl2 = contractDetail.lines.find(line => line.productId === p2.id);
const firstShipment = await ok(`/contracts/${contract.id}/ship`, { version: 2, document_number: `DN-${tag}-1`, lines: [{ line_id: sl1.id, quantity: 1 }] });
assert.equal(firstShipment.status, 'partial_shipped');
assert.equal(Number(firstShipment.receivable.amount), 30);
assert.equal((await request(`/contracts/${contract.id}/ship`, { version: 3, lines: [{ line_id: sl1.id, quantity: 4 }] })).status, 409, 'overshipment must be rejected');
await login(accountant, password);
const receivable = (await ok('/finance/receivables')).find(account => account.contractId === contract.id);
await ok(`/finance/receivables/${receivable.id}/payments`, { amount: '30.00', reference: `REC-${tag}` });
assert.equal((await request(`/finance/receivables/${receivable.id}/payments`, { amount: '1.00', reference: `REC-${tag}` })).status, 409, 'duplicate receivable reference must be rejected');
await login(keeper, password);
const finalShipment = await ok(`/contracts/${contract.id}/ship`, { version: 3, document_number: `DN-${tag}-2`, lines: [{ line_id: sl1.id, quantity: 3 }, { line_id: sl2.id, quantity: 2 }] });
assert.equal(finalShipment.status, 'shipped');
assert.equal(Number(finalShipment.receivable.amount), 200);
assert.equal(finalShipment.receivable.status, 'partial');
assert.equal((await ok(`/contracts/${contract.id}`)).stockDocuments.length, 2);
const stock = await ok('/inventory');
assert.equal(stock.find(row => row.productId === p1.id).quantity, 1);
assert.equal(stock.find(row => row.productId === p2.id).quantity, 1);
assert.equal(stock.find(row => row.productId === p1.id).product.reorderPoint, 2);
assert.equal((await ok('/inventory/movements')).filter(row => [p1.id, p2.id].includes(row.productId)).length, 6);
const stocktake = await ok('/inventory/stocktakes', { document_number: `ST-${tag}`, note: '样品盘点', lines: [{ product_id: p1.id, counted_qty: 3 }, { product_id: p2.id, counted_qty: 0 }] });
assert.equal(stocktake.movements.length, 2);
assert.equal((await ok('/inventory')).find(row => row.productId === p1.id).quantity, 3);
assert.equal((await ok('/inventory')).find(row => row.productId === p2.id).quantity, 0);
assert.equal((await request('/inventory/stocktakes', { document_number: `ST-${tag}`, lines: [{ product_id: p1.id, counted_qty: 4 }] })).status, 409, 'duplicate stocktake number must not change stock');
assert.equal((await ok('/inventory')).find(row => row.productId === p1.id).quantity, 3);
assert.ok((await ok('/inventory/documents')).some(document => document.id === stocktake.id));
await login(seller, password);
assert.equal((await request('/inventory/stocktakes', { document_number: `FORBIDDEN-${tag}`, lines: [{ product_id: p1.id, counted_qty: 4 }] })).status, 403);
console.log('ERP partial stock flow passed: batch receipts/shipments, incremental accounts, stocktake, duplicate references, rollback and roles.');
